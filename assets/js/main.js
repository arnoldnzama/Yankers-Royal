document.addEventListener('DOMContentLoaded', () => {
  // 1. Language Switcher (FR / EN)
  let currentLang = localStorage.getItem('yankers_lang') || 'fr';

  function applyLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('yankers_lang', lang);

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        el.textContent = translations[lang][key];
      }
    });

    // Mettre à jour la classe active sur les boutons FR / EN
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });
  }

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const selected = btn.getAttribute('data-lang');
      applyLanguage(selected);
    });
  });

  applyLanguage(currentLang);

  // 2. Splash Screen Motion Animation
  const splashScreen = document.getElementById('splash-screen');
  if (splashScreen) {
    window.addEventListener('load', () => {
      setTimeout(() => {
        splashScreen.classList.add('fade-out');
      }, 1400);
    });
    setTimeout(() => {
      splashScreen.classList.add('fade-out');
    }, 2400);
  }

  // 3. Header Scroll Effect
  const header = document.querySelector('.site-header');
  window.addEventListener('scroll', () => {
    if (window.scrollY > 40) {
      header?.classList.add('scrolled');
    } else {
      header?.classList.remove('scrolled');
    }
  });

  // 4. Mobile Navigation Toggle & Outside Click
  const mobileToggle = document.querySelector('.btn-mobile-toggle');
  const navMenu = document.querySelector('.nav-menu');
  if (mobileToggle && navMenu) {
    mobileToggle.addEventListener('click', (e) => {
      e.stopPropagation();
      navMenu.classList.toggle('open');
      const icon = mobileToggle.querySelector('i');
      if (icon) {
        icon.classList.toggle('fa-bars');
        icon.classList.toggle('fa-xmark');
      }
    });

    document.addEventListener('click', (e) => {
      if (!navMenu.contains(e.target) && !mobileToggle.contains(e.target) && navMenu.classList.contains('open')) {
        navMenu.classList.remove('open');
        const icon = mobileToggle.querySelector('i');
        if (icon) {
          icon.classList.add('fa-bars');
          icon.classList.remove('fa-xmark');
        }
      }
    });
  }

  // 5. Automatic Hero Slider with Motion (4s)
  const slides = document.querySelectorAll('.hero-slide');
  let currentSlide = 0;
  let sliderInterval = null;

  function showSlide(index) {
    if (!slides.length) return;
    slides.forEach((s, idx) => {
      s.classList.toggle('active', idx === index);
    });
    currentSlide = index;
  }

  function nextSlide() {
    let next = (currentSlide + 1) % slides.length;
    showSlide(next);
  }

  function startAutoSlider() {
    if (sliderInterval) clearInterval(sliderInterval);
    sliderInterval = setInterval(nextSlide, 4000);
  }

  if (slides.length > 0) {
    startAutoSlider();
  }

  // 6. Interactive Search Inputs
  const personSelect = document.getElementById('person-select');
  const personValueLabel = document.getElementById('person-value-label');
  if (personSelect && personValueLabel) {
    personSelect.addEventListener('change', (e) => {
      personValueLabel.textContent = e.target.value;
    });
  }

  const checkInInput = document.getElementById('checkin-input');
  const checkInValueLabel = document.getElementById('checkin-value-label');
  if (checkInInput && checkInValueLabel) {
    checkInInput.addEventListener('change', (e) => {
      checkInValueLabel.textContent = e.target.value || 'Start';
    });
  }

  const checkOutInput = document.getElementById('checkout-input');
  const checkOutValueLabel = document.getElementById('checkout-value-label');
  if (checkOutInput && checkOutValueLabel) {
    checkOutInput.addEventListener('change', (e) => {
      checkOutValueLabel.textContent = e.target.value || 'Until';
    });
  }

  const btnSearch = document.querySelector('.btn-search-hero');
  if (btnSearch) {
    btnSearch.addEventListener('click', () => {
      const p = personSelect ? personSelect.value : '2 Adults';
      const ci = checkInInput && checkInInput.value ? checkInInput.value : 'Aujourd\'hui';
      const co = checkOutInput && checkOutInput.value ? checkOutInput.value : 'Demain';
      
      btnSearch.style.transform = 'scale(0.96)';
      setTimeout(() => {
        btnSearch.style.transform = '';
        window.location.href = `booking.html?guests=${encodeURIComponent(p)}&in=${encodeURIComponent(ci)}&out=${encodeURIComponent(co)}`;
      }, 150);
    });
  }

  // 7. Booking Category Ribbon Interaction
  const categoryPills = document.querySelectorAll('.category-pill');
  categoryPills.forEach(pill => {
    pill.addEventListener('click', () => {
      categoryPills.forEach(p => p.classList.remove('active'));
      pill.classList.add('active');
    });
  });

  // 8. Intersection Observer for Scroll Motion
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('motion-in-view');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1 });

  document.querySelectorAll('.hospitality-card, .benefit-item, .section-head, .room-card, .result-hotel-item').forEach(el => {
    el.style.opacity = '0';
    el.style.transform = 'translateY(24px)';
    el.style.transition = 'opacity 0.65s cubic-bezier(0.16, 1, 0.3, 1), transform 0.65s cubic-bezier(0.16, 1, 0.3, 1)';
    observer.observe(el);
  });

  document.head.insertAdjacentHTML('beforeend', `
    <style>
      .motion-in-view {
        opacity: 1 !important;
        transform: translateY(0) !important;
      }
    </style>
  `);
});
